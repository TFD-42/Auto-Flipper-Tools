#!/usr/bin/env python3
"""
BadUSB payload preparation agent — semi-interactive, Ollama-assisted.

Role: prepare classified scripts (see classify_badusb.py) before the user
copies them onto the Flipper Zero's SD card themselves (into badusb/). This
script never touches the SD card directly.

For each script:
  1. Deterministic (regex) detection of fields to customize — Discord
     webhook, Telegram bot/chat, attacker IP/port, email, bracket
     placeholders ([person], [text]...), API key. See FIELD_SPECS.
  2. If regex finds nothing, an optional fallback asks an Ollama model
     (tool-calling, never blindly-parsed free text — same philosophy as
     Bad_USB_Classifier/ollama_agent.py) whether it spots a field to
     configure. Any value returned by the model is re-verified verbatim in
     the file before being used: no blind replacement.
  3. Scripts with no detected field are copied as-is (no action needed —
     "plug and play").
  4. For scripts with detected fields, the user is asked once per field
     type (global value reused) or file by file depending on their choice
     — see collect_field_values().

See SETUP_METHODS.md (generated by --write-methods-doc) for the method used
per classification theme.
"""
